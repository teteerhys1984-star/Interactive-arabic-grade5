/*
 * Load-time invariant: every suggested answer must belong to a real activity of
 * this lesson, and it must be attached to a record declared `guidance_only`.
 * A suggestion on a `no_approved_content` record (or on a missing id) would be
 * content that the disclosure never allows through — a contradiction that must
 * fail loudly instead of silently disappearing.
 */
const GUIDANCE_IDS = Object.keys(U3L1_SUGGESTED_ANSWERS);

GUIDANCE_IDS.forEach((id) => {
  const activity = U3L1_ACTIVITY_BY_ID[id];
  if (!activity) {
    throw new Error(`src/data/unit3Lesson1/guidance.ts: إرشاد لنشاط غير موجود (${id})`);
  }
  if (activity.disclosure.kind !== 'guidance_only') {
    throw new Error(
      `src/data/unit3Lesson1/guidance.ts: إرشاد على نشاط لا يعلن «guidance_only» (${id}: ${activity.disclosure.kind})`,
    );
  }
});

/** Activities that deliberately carry no suggested answer (missing source). */
export const U3L1_UNDECIDABLE_IDS = U3L1_ACTIVITIES_WITHOUT_GUIDANCE();

function U3L1_ACTIVITIES_WITHOUT_GUIDANCE(): string[] {
  return Object.values(U3L1_ACTIVITY_BY_ID)
    .filter((activity) => !U3L1_SUGGESTED_ANSWERS[activity.id])
    .map((activity) => activity.id);
}

/**
 * Builds the record the SHARED resolver consumes. The disclosure is the
 * activity's own (never overridden here), so nothing becomes visible that the
 * data did not declare, and the eight gap records stay button-less.
 */
export function u3l1RevealRecord(activity: U3L1Activity): DisclosureBearingRecord {
  const suggested = U3L1_SUGGESTED_ANSWERS[activity.id];
  return {
    id: activity.id,
    sourceActivityId: activity.sourceActivityId,
    disclosure: activity.disclosure,
    modelAnswer: suggested?.modelAnswer,
    explanation: suggested?.explanation,
  };
}
